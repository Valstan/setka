-- 093: журнал отсеянных дублей (заказ владельца 2026-08-30).
--
-- ЗАЧЕМ. Одна и та же новость выходит в ленте дважды. Разбор показал, что
-- внутриволновой дедуп этого НЕ лечит: проигравший нигде не запоминается, и
-- через пару часов следующая волна берёт его как свежий пост — конкурента рядом
-- уже нет, текст переписан (мимо txtfp/txtcore), фото перезалито (мимо
-- photo_{owner}_{id}) — и он публикуется. Дубль не устранялся, а сдвигался.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ work_tables.lip. Решение владельца дословно:
-- «если в опубликованные, то нехорошо, потому что это потом в статистике
-- отобразится нехорошо». Курсор work_tables.lip означает «опубликовано» и
-- питает счётчики; складывать туда неопубликованное значило бы врать статистике.
-- Плюс у него потолок 1000 записей, и дубли вытесняли бы историю публикаций.
--
-- ЧТО СЮДА НЕ ПОПАДАЕТ. Пост, который просто не влез в тройку сводки, — НЕ дубль
-- и в эту таблицу не пишется: у него должен остаться шанс выйти следующей волной,
-- пока не кончилось окно свежести. Здесь только те, у кого нашёлся более ранний
-- близнец.
--
-- РЕТЕНШЕН. Запись нужна ровно столько, сколько пост может ещё оказаться
-- кандидатом, то есть max_post_age_hours (дефолт 72 ч). Держим неделю с запасом
-- и чистим — таблица остаётся маленькой, а ложное срабатывание существующего
-- текстового дедупа само рассасывается через неделю, а не навсегда.
--
-- original_lip — кого признали первоисточником. NULL, когда близнец найден в
-- истории волн, а не в этой волне: там первоисточник уже опубликован и его lip
-- лежит в work_tables.
--
-- Без собственных BEGIN/COMMIT — их даёт scripts/migrate.py (см. шапку 090).
-- Время в UTC, как пишет приложение (см. 092).

CREATE TABLE IF NOT EXISTS skipped_duplicates (
    id BIGSERIAL PRIMARY KEY,
    lip VARCHAR(50) NOT NULL,
    region_code VARCHAR(50) NOT NULL,
    original_lip VARCHAR(50),
    reason VARCHAR(32) NOT NULL DEFAULT 'duplicate',
    wave_theme VARCHAR(50),
    detected_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'UTC')
);

-- Основной запрос: «какие lip'ы региона уже отсеяны как дубли» — читается на
-- каждой волне и подмешивается к курсору дедупа.
CREATE UNIQUE INDEX IF NOT EXISTS uq_skipped_duplicates_region_lip
    ON skipped_duplicates (region_code, lip);

-- Ретеншен и разбор глазами.
CREATE INDEX IF NOT EXISTS ix_skipped_duplicates_detected
    ON skipped_duplicates (detected_at);

