-- 105: ЕСА перестаёт врать про время входа (`auth_time`).
--
-- Почему. `auth_time` в ID-токене — это ответ на вопрос клиента «когда человек
-- реально аутентифицировался»; на нём клиент решает, пора ли переспросить пароль
-- (OIDC `max_age`, `prompt=login`). До этой миграции ЕСА не знал ответа и всё
-- равно его давал:
--   * `oauth_auth_codes.auth_time` заполнялся моментом ВЫДАЧИ КОДА
--     (`issue_auth_code`: `auth_time=now`), а не моментом входа;
--   * на обновлении токенов `auth_time` брался из `_utcnow()` — то есть каждый
--     refresh утверждал, что вход состоялся только что. Это хуже первого: сессия
--     недельной давности выглядела свежей ровно настолько, насколько часто
--     клиент обновлял токен.
-- Согласовано с мозгом 2026-09-15: сперва честный `auth_time` (`iat` в сессии),
-- `prompt`/`max_age` — следующим шагом. Ложный `auth_time` хуже отсутствующего:
-- клиент, послушавшийся документации, получит тот же отказ тише.
--
-- Что делает миграция. Две колонки под ПЕРЕНОС времени входа, обе NULL-able:
--   1. `oauth_auth_codes.auth_time` — снимаем NOT NULL. NULL = «время входа
--      неизвестно» (сессионная cookie выдана до появления `iat` в payload).
--      Тогда claim `auth_time` не заявляется вовсе — отсутствующий честнее
--      подставленного.
--   2. `oauth_refresh_tokens.auth_time` — новая колонка: время входа едет по
--      цепочке ротаций неизменным, потому что обновление токена аутентификацией
--      не является.
--
-- Совместимость. Аддитивно и обратимо; действующие сессии и выданные токены
-- остаются валидными — у них `auth_time` просто NULL до следующего входа.
-- Применение: обычный `psql -f`, рестарт веба нужен (код читает новые поля).
-- Откат: `ALTER TABLE oauth_refresh_tokens DROP COLUMN auth_time;` и возврат
-- NOT NULL возможен только после заполнения — поэтому откат схемы не
-- предполагается, достаточно отката кода.

ALTER TABLE oauth_auth_codes ALTER COLUMN auth_time DROP NOT NULL;

ALTER TABLE oauth_refresh_tokens ADD COLUMN IF NOT EXISTS auth_time TIMESTAMP NULL;

COMMENT ON COLUMN oauth_auth_codes.auth_time IS
    'Когда человек реально аутентифицировался (iat сессии). NULL — неизвестно, claim не заявляем.';
COMMENT ON COLUMN oauth_refresh_tokens.auth_time IS
    'Время входа, перенесённое по цепочке ротаций. NULL — неизвестно, claim не заявляем.';
