-- 089: счётчик неудачных попыток отправки в work_tables (2026-08-28).
--
-- ЗАЧЕМ. Зеркало Flow B (стена ВК → Telegram) ретраит пост, пока не доставит.
-- Ограничителем служил только возраст поста (GONBA_MAX_POST_AGE_HOURS=48), то
-- есть до ~96 попыток на пост при расписании «каждые 30 минут». Пока отказ
-- честный (не доставлено ничего), это лишь шум в логах. Но отказ бывает и
-- лживым: read-timeout означает «ответ потерян», а не «сообщение не дошло» —
-- и тогда неограниченный повтор снова превращается в спам в живом канале.
-- Ровно этот класс уже стрелял 27-28.08 в @gonba_life, только через другую
-- дверь (частичная доставка считалась провалом, PR #545).
--
-- ПОЧЕМУ ЗДЕСЬ, А НЕ В ОТДЕЛЬНОЙ ТАБЛИЦЕ. Счётчик обязан двигаться атомарно с
-- курсором дедупликации: «сдались после N попыток» = «пост помечен отправленным»,
-- и разъехаться эти два факта не должны ни при каком падении между коммитами.
-- Курсор живёт в work_tables.lip той же строки — значит и счётчик тоже, в том же
-- session.commit().
--
-- ФОРМАТ: {"<lip>": <число попыток>}, например {"218688001_7572": 2}.
-- NULL = провалов нет. Словарь самоочищается: зеркало держит в нём только те lip,
-- которые ещё видны в текущем окне стены и ещё не помечены отправленными, —
-- поэтому он не растёт неограниченно и не требует отдельной чистки.
--
-- Идемпотентна (ADD COLUMN IF NOT EXISTS). Применять с ON_ERROR_STOP=1.
-- Данных не трогает: колонка nullable, дефолт NULL, существующие строки как были.

ALTER TABLE work_tables ADD COLUMN IF NOT EXISTS failed_attempts JSON;

