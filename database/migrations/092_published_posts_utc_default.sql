-- 092: время в журнале публикаций — UTC, как во всём приложении (2026-08-30).
--
-- ЗАЧЕМ. Миграция 091 завела published_at с `DEFAULT now()`, повторив конвенцию
-- соседних таблиц. На проде это ловушка: `SHOW timezone` = Host, и `now()`
-- отдаёт МОСКОВСКОЕ время (19:26), тогда как приложение пишет наивный UTC
-- (16:26) — модели стоят на `datetime.utcnow`. Разница ровно три часа.
--
-- Сегодня не стреляет: строки создаёт ORM, а он всегда подставляет значение сам,
-- и дефолт базы не срабатывает ни разу. Но у ЭТОЙ таблицы всё назначение —
-- арифметика по временному окну: fetch_published_counts берёт
-- `utcnow() - window_hours`. Одна строка, вставленная SQL-ом без published_at,
-- на три часа оказалась бы «в будущем» и всё это время завышала бы расход своей
-- темы — то есть душила бы ровно ту рубрику, которую владелец разрешил.
-- Чинится дешевле всего сейчас, пока в таблице две строки.
--
-- ПОЧЕМУ ТОЛЬКО ЗДЕСЬ. Тот же перекос заложен и в соседних таблицах (069, 080 и
-- далее), но там дефолт тоже не срабатывает, а ширина окна больше и цена ошибки
-- ниже. Массовая правка конвенции — отдельная работа с отдельным замером;
-- записана техдолгом в PENDING_FOLLOWUPS.
--
-- Идемпотентна (SET DEFAULT переустанавливает то же значение).
-- Без собственных BEGIN/COMMIT — их даёт scripts/migrate.py (см. шапку 090).

ALTER TABLE published_posts
    ALTER COLUMN published_at SET DEFAULT (now() AT TIME ZONE 'UTC');

