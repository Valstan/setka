-- 079: словарь синонимов тем классификатора — замок на дверь, которую открыла 070.
--
-- Миграция 069 завела канонический словарь тем (12 штук), 070 разово
-- нормализовала историю по временной таблице синонимов. Временная таблица
-- умерла вместе с транзакцией, а на запись канон никто не применял:
-- record_verdicts кладёт verdict['theme'] ровно так, как прислала модель.
--
-- Итог на 2026-08-09: с момента нормализации (07-19) записано 1992 вердикта
-- с 29 неканоническими темами, поток идёт текущим днём. Одна «реклама»
-- размазана по шести написаниям, включая смешанные кириллицу с латиницей
-- («рекламa» с латинской a, «рeklama»). Тема — ось всей петли HITL: по ней
-- считается agree-rate, по ней группируются правила overlay, по ней идёт
-- дистилляция. Расщепление бьёт ровно по тому механизму, ради которого
-- Корпус копится.
--
-- Синонимы живут таблицей, а не константой в коде, по той же причине, по
-- которой темами управляет оператор: список синонимов — редакционное знание,
-- и правка «ещё одно написание рекламы» не должна требовать релиза.
--
-- Сид ниже — синонимы из словаря 070 плюс написания, реально встреченные в
-- Корпусе. Неоднозначные значения («неопределено», «мероприятия», «туризм»,
-- «рекреация», «благоустройство», «hold») сюда НЕ включены осознанно:
-- угадать их канон нельзя, а тихая подгонка потока под словарь — ровно та
-- ошибка, которую здесь и лечим. Они останутся неканоническими, попадут в
-- лог и в редактор как кандидаты — решает оператор.
--
-- Идемпотентно. Откат: DROP TABLE classifier_theme_aliases;

CREATE TABLE IF NOT EXISTS classifier_theme_aliases (
    id BIGSERIAL PRIMARY KEY,
    -- написание, встреченное в вердикте; хранится уже приведённым к нижнему
    -- регистру и без крайних пробелов — нормализатор ищет по этому же виду
    alias VARCHAR(200) NOT NULL,
    -- каноническая тема; FK не ставим намеренно: классификатор не должен
    -- падать на записи вердикта из-за того, что оператор удалил тему в
    -- редакторе. Висячий canon виден в редакторе и чинится там же.
    canon VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_classifier_theme_aliases_alias
    ON classifier_theme_aliases (alias);

