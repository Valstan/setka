-- 091: журнал публикаций — что и когда реально вышло на стену (заказ владельца 2026-08-30).
--
-- ЗАЧЕМ. Владелец задаёт долю темы в ленте («новости 50%, детсады 5%»), а доля
-- считается ОТ ЧЕГО-ТО. Считать не от чего: в системе нет ответа на вопрос
-- «какие посты и когда мы опубликовали».
--
-- Почему не подошёл ни один существующий журнал:
--   * work_tables.lip   — курсор дедупа, а не журнал: без времени по каждому lip
--                         и с потолком 1000 записей (append_unique_limited режет
--                         хвост). Долю за окно из него не посчитать.
--   * bulletin_curation_runs — под гейтом BULLETIN_CURATION_SHADOW_ENABLED и
--                         allowlist'ом из одного района; хранит текст до 3000
--                         символов на кандидата, при снятии гейта это мегабайты
--                         в сутки. И темы вердикта в нём нет.
--   * collected_post_audit — про посты-ИСТОЧНИКИ (обе стороны фильтра), тоже под
--                         гейтом, а theme в нём — тема ВОЛНЫ, не тема вердикта.
--   * parsing_stats     — только счётчик posts_final_count, снятый ДО отбора и
--                         ДО отсечки max_posts_per_bulletin. Какие посты вышли,
--                         он не знает.
--
-- ПОЧЕМУ БЕЗ ГЕЙТА, в отличие от соседних журналов. Гейтованный журнал считает
-- по дырявым данным: доля темы, посчитанная по одному району из двадцати девяти,
-- описывает не сеть, а этот район. Квота — механизм принятия решений, её вход
-- обязан быть полным. Строк ~1200 в сутки, ретеншен снимает старые.
--
-- ДВЕ ТЕМЫ В ОДНОЙ СТРОКЕ — не дублирование, они про разное:
--   wave_theme    — тема ВОЛНЫ (novost, kultura, sport…): откуда собирали и под
--                   какой шапкой публиковали. Известна всегда.
--   verdict_theme — тема ВЕРДИКТА (новости, спорт, кругозор…): что в посте по
--                   содержанию, по мнению нейросети. Именно ею управляет владелец
--                   на странице долей. NULL = вердикта не было (режим деградации
--                   algorithmic-fallback или пост без текста).
-- Первая нужна для сверки с parsing_stats, вторая — для квот.
--
-- source_region_code — чей пост перепечатали (витрина соседа, PR 5). NULL для
-- собственных публикаций района.
--
-- БЕЗ UNIQUE(region_code, lip). Ретрай Celery после успешной публикации
-- задвоил бы строку, но UNIQUE + ON CONFLICT DO NOTHING НЕДОсчитывал бы законную
-- повторную публикацию того же поста через месяцы. Недосчёт квоты тише
-- пересчёта: он молча ослабляет потолок, тогда как лишняя строка видна в журнале
-- глазами. В текущем коде запись идёт последним шагом волны, после публикации,
-- так что задвоение и не воспроизводится.
--
-- БЕЗ СОБСТВЕННЫХ BEGIN/COMMIT — их даёт scripts/migrate.py вместе с записью в
-- applied_migrations (см. шапку 090). Применять: python3 scripts/migrate.py up.

CREATE TABLE IF NOT EXISTS published_posts (
    id BIGSERIAL PRIMARY KEY,
    lip VARCHAR(50) NOT NULL,
    region_code VARCHAR(50) NOT NULL,
    wave_theme VARCHAR(50) NOT NULL,
    verdict_theme VARCHAR(100),
    kind VARCHAR(20) NOT NULL DEFAULT 'regular',
    source_region_code VARCHAR(50),
    published_url VARCHAR(500),
    published_at TIMESTAMP NOT NULL DEFAULT now()
);

-- Основной запрос квоты: «сколько постов темы T опубликовал регион R за окно».
-- Регион первым — он самый селективный (двадцать девять значений), время
-- убыванием — окно всегда свежее.
CREATE INDEX IF NOT EXISTS ix_published_posts_region_theme_time
    ON published_posts (region_code, verdict_theme, published_at DESC);

-- Знаменатель квоты и ретеншен: «всё, что регион опубликовал за окно».
CREATE INDEX IF NOT EXISTS ix_published_posts_region_time
    ON published_posts (region_code, published_at DESC);

