UPDATE classifier_themes SET position = 7, is_service = FALSE, description =
    'Познавательное: наука, техника, история, природа, путешествия, '
    'занимательное о мире и музыке. НЕ бытовое — огород, рассада, вязание, '
    'рукоделие, готовка и рецепты сюда НЕ относятся, это «мусор».'
