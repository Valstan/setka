-- 090: перегруппировка словаря тем 12→9 + доли наполнения ленты (заказ владельца 2026-08-30).
--
-- ЗАЧЕМ. Словарь тем разросся до 21 варианта: 12 канонических (миграция 069) плюс
-- девять свободных, которые нейросеть насочиняла мимо словаря — «туризм»,
-- «рекреация», «жалоба», «благоустройство», «рекламаслуг», два написания
-- «праздники» и даже «Клуб Малмыжских Путешественников» (название сообщества
-- принято за тему). Управлять наполнением ленты по такому списку нельзя: у
-- владельца должно быть семь рычагов, а не двадцать один.
--
-- Итоговый состав — вариант «А» владельца: семь рабочих тем, у каждой свой
-- процент наполнения, плюс две служебные, которые процентов не едят.
--
--   новости · администрация · объявления · культура · спорт ·
--   дети и образование · кругозор        + служебные: соседи, мусор
--
-- ПРАВОСЛАВИЕ УДАЛЯЕТСЯ ЦЕЛИКОМ. Замер: 643 вердикта за 30 дней, из них
-- подавляющее большинство с action=publish — выученное правило id=7
-- (утв. 2026-07-10) прямо предписывало публиковать религиозные события, а отбор
-- apply_wave_selection читает только action и тему игнорирует. Тема схлопывается
-- в «мусор»; правило id=7 ретайрится отдельным шагом через UI (обратимо), и
-- отдельным гейтованным шагом старым вердиктам проставляется hold — смена
-- правила влияет только на новые.
--
-- ПОЧЕМУ СЕМЬ ИМЁН ИЗ ДЕВЯТИ НЕ МЕНЯЮТСЯ. Переименование каждой темы означает
-- переписывание её вердиктов: у «новостей» это 13 262 строки за 30 дней при
-- 74 782 всего. Сохраняя написание, мы трогаем только те 5% строк, что реально
-- меняют тему. Регистр тоже сохраняем нижний — таким словарь был с 069, а
-- canonicalize_theme сравнивает без учёта регистра.
--
-- ПОЧЕМУ SQL, А НЕ service.reassign_theme. Питоновский перенос грузит ВСЕ строки
-- content_classifications в память и делает это один раз на тему — тринадцать
-- проходов по 74 782 строкам. Здесь тот же результат одним UPDATE на группу.
--
-- НОВЫЕ КОЛОНКИ.
--   share_percent — доля темы в ленте: NULL = не ограничивать (дефолт всем),
--                   0 = запрещена, >0 = потолок в процентах. Не нормируется на
--                   сумму: каждая доля — независимый потолок, поэтому сумма ≠ 100
--                   движок не ломает и частичная настройка безопасна.
--   description   — что входит в тему. Уходит в промпт нейросети рядом с именем
--                   (rules.py, блок «Разрешённые темы»). Это единственный способ
--                   объяснить движку «кругозор»: наука и путешествия — да,
--                   огород и вязание — нет. Раньше объяснять было негде, отсюда и
--                   «Клуб Малмыжских Путешественников» в роли темы.
--   is_service    — служебная тема, процентов не получает. Без флага «мусор» и
--                   «соседи» показывались бы на странице с ползунками, которые
--                   ничего не делают: мусор не публикуется вовсе, а соседи идут
--                   отдельным каналом со своим расписанием.
--
-- Идемпотентна: ADD COLUMN IF NOT EXISTS, INSERT ... ON CONFLICT DO NOTHING,
-- UPDATE по спискам исчезнувших имён (второй прогон не найдёт ничего).
-- Применять с ON_ERROR_STOP=1.

BEGIN;

-- 1. Новые колонки словаря ------------------------------------------------

ALTER TABLE classifier_themes ADD COLUMN IF NOT EXISTS share_percent NUMERIC(5,2);
ALTER TABLE classifier_themes ADD COLUMN IF NOT EXISTS description TEXT;
ALTER TABLE classifier_themes ADD COLUMN IF NOT EXISTS is_service BOOLEAN NOT NULL DEFAULT FALSE;

-- 2. Две новые темы -------------------------------------------------------

INSERT INTO classifier_themes (name, position) VALUES
    ('дети и образование', 6),
    ('кругозор', 7)
ON CONFLICT (name) DO NOTHING;

-- 3. Перенос вердиктов ----------------------------------------------------
-- Порядок групп не важен: списки-источники не пересекаются и не содержат имён
-- тем-получателей, поэтому ни один UPDATE не переносит то, что уже перенёс
-- предыдущий.

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"новости"')
 WHERE verdict->>'theme' IN ('происшествия', 'благоустройство');

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"объявления"')
 WHERE verdict->>'theme' IN ('рекламаслуг', 'жалоба');

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"культура"')
 WHERE verdict->>'theme' IN ('Праздники', 'праздники');

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"дети и образование"')
 WHERE verdict->>'theme' IN ('образование', 'детский сад');

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"кругозор"')
 WHERE verdict->>'theme' IN (
        'научпоп', 'туризм', 'рекреация', 'Клуб Малмыжских Путешественников'
       );

UPDATE content_classifications
   SET verdict = jsonb_set(verdict, '{theme}', '"мусор"')
 WHERE verdict->>'theme' IN ('православие', 'неопределено');

-- 4. Перенос правок оператора --------------------------------------------
-- operator_value хранится JSON-скаляром ("объявления"), поэтому сравниваем через
-- #>> '{}'. Человеческая правка — самый ценный материал Корпуса: потерять её при
-- перегруппировке значило бы стереть то, ради чего ведётся дистилляция.

UPDATE classification_corrections
   SET operator_value = '"новости"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN ('происшествия', 'благоустройство');

UPDATE classification_corrections
   SET operator_value = '"объявления"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN ('рекламаслуг', 'жалоба');

UPDATE classification_corrections
   SET operator_value = '"культура"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN ('Праздники', 'праздники');

UPDATE classification_corrections
   SET operator_value = '"дети и образование"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN ('образование', 'детский сад');

UPDATE classification_corrections
   SET operator_value = '"кругозор"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN (
        'научпоп', 'туризм', 'рекреация', 'Клуб Малмыжских Путешественников'
       );

UPDATE classification_corrections
   SET operator_value = '"мусор"'::jsonb
 WHERE verdict_type = 'theme'
   AND operator_value #>> '{}' IN ('православие', 'неопределено');

-- 5. Синонимы -------------------------------------------------------------
-- Durable-карта на будущее: движок ещё какое-то время будет отдавать старые
-- имена (промпт кэшируется у провайдера, да и просто по инерции), а
-- canonicalize_theme применяется на КАЖДОЙ записи вердикта. Без этих строк
-- «происшествия» вернулись бы в базу не-каноном сразу после миграции.
-- alias хранится в нижнем регистре — этого требует таблица (см. миграцию 079).

INSERT INTO classifier_theme_aliases (alias, canon) VALUES
    ('происшествия',                     'новости'),
    ('благоустройство',                  'новости'),
    ('рекламаслуг',                      'объявления'),
    ('жалоба',                           'объявления'),
    ('праздники',                        'культура'),
    ('образование',                      'дети и образование'),
    ('детский сад',                      'дети и образование'),
    ('дошкольное образование',           'дети и образование'),
    ('школа',                            'дети и образование'),
    ('научпоп',                          'кругозор'),
    ('наука',                            'кругозор'),
    ('туризм',                           'кругозор'),
    ('путешествия',                      'кругозор'),
    ('рекреация',                        'кругозор'),
    ('клуб малмыжских путешественников', 'кругозор'),
    ('православие',                      'мусор'),
    ('религия',                          'мусор'),
    ('неопределено',                     'мусор')
ON CONFLICT (alias) DO UPDATE SET canon = EXCLUDED.canon;

-- 6. Удаление отработавших тем -------------------------------------------

DELETE FROM classifier_themes
 WHERE name IN ('происшествия', 'образование', 'детский сад', 'православие', 'научпоп');

-- 7. Позиции, описания, служебность --------------------------------------
-- description уходит в промпт. Формулировки — из разбора Корпуса (DISTILL_LOG
-- 18-20.08) и прямых решений владельца, поэтому здесь они конкретные, а не
-- «новости — это новости»: движку нужна граница, а не синоним.

UPDATE classifier_themes SET position = 1, is_service = FALSE, description =
    'Что произошло в районе: события, происшествия и ЧП, работа служб, '
    'местная повестка, сообщения жителей о случившемся.'
 WHERE name = 'новости';

UPDATE classifier_themes SET position = 2, is_service = FALSE, description =
    'Официальные сообщения администрации района и поселений, депутатов, '
    'госучреждений: решения, графики работ, отключения, приёмы граждан.'
