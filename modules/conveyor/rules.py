"""Правила сайта для LLM-стадии конвейера — файл на сайт (D-015, мандат §4).

Мандат brain 2026-08-08 просит **общий базовый файл + сайтовую надстройку**, и
причина у разделения не эстетическая: дистилляция коррекций владельца идёт
раздельно по сайтам («у ДК и портала разные вкусы»), а часть решений всё-таки
общая для кластера. Один файл на всех превратил бы правку одного сайта в порчу
остальных; отдельные файлы без общей части заставили бы дублировать одно и то же
редакционное решение столько раз, сколько сайтов, — и расходиться молча.

Порядок склейки — база, затем надстройка, и это тоже решение, а не случайность:
модель читает инструкции подряд, и то, что идёт позже, для неё весомее. Сайтовое
правило обязано побеждать общее, иначе надстройка бессмысленна. То же сказано и
словами в шапке, чтобы правило не держалось на одном лишь порядке строк.

Файлы редактируются человеком и живут в git: правило «федеральный календарь — не
история района» должно меняться правкой одной строки в markdown, без релиза кода.
Отсутствие файлов — штатное состояние (пустая строка), а не ошибка: сайт может
работать на одном системном промпте, пока для него не накопились правила.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)

# Имя общего файла. Подчёркивание — чтобы он не мог столкнуться с ключом сайта:
# ключи приходят из ``SITES`` в нижнем регистре без подчёркивания в начале.
BASE_FILE = "_base.md"

# Потолок на склеенные правила. Файл правил растёт дистилляцией (§C плана,
# потолок ~100 правил), а промпт уходит в оплачиваемый вызов на каждый пост.
# Разросшийся файл не должен незаметно превратиться в счёт за токены — поэтому
# лишнее обрезается, а факт обрезки пишется в лог: это сигнал «пора дистиллировать
# правила», а не повод уронить прогон.
MAX_RULES_CHARS = 8000


def get_rules_dir() -> Path:
    """Каталог правил: env ``CONVEYOR_RULES_DIR`` либо ``rules/`` в корне репо.

    Env-override нужен тестам и разовым прогонам «а что будет с другим сводом
    правил» — без него проверка правил требовала бы правки файлов в рабочем дереве.
    """
    raw = (os.getenv("CONVEYOR_RULES_DIR") or "").strip()
    if raw:
        return Path(raw)
    return Path(__file__).resolve().parents[2] / "rules"


def _read(path: Path) -> str:
    """Прочитать файл правил. Нет файла или нечитаем — пусто, без исключения.

    Конвейер — фоновая рутина: отсутствие необязательного файла не должно
    отменять прогон. А вот нечитаемый файл (права, битая кодировка) — это уже
    неожиданность, и она попадает в лог, чтобы не выглядеть как «правил нет».
    """
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return ""
    except OSError as e:
        logger.warning("правила конвейера: не прочитан %s (%s)", path, e)
        return ""
    except ValueError as e:  # битая кодировка
        logger.warning("правила конвейера: не декодирован %s (%s)", path, e)
        return ""


def load_rules(site_key: str, *, rules_dir: Optional[Path] = None) -> str:
    """Правила для сайта: общая база + надстройка сайта, склеенные для промпта.

    Возвращает пустую строку, если нет ни одного файла, — вызывающему не нужно
    различать «правил нет» и «файлов нет».
    """
    key = (site_key or "").strip().lower()
    directory = rules_dir if rules_dir is not None else get_rules_dir()

    base = _read(directory / BASE_FILE).strip()
    site = _read(directory / f"{key}.md").strip() if key else ""
    if not base and not site:
        return ""

    parts = []
    if base:
        parts.append("# Общие правила кластера\n\n" + base)
    if site:
        parts.append("# Правила этого сайта (важнее общих при конфликте)\n\n" + site)
    joined = "\n\n".join(parts)

    if len(joined) > MAX_RULES_CHARS:
        logger.warning(
            "правила конвейера %s: %s символов > потолка %s — обрезаны, пора дистиллировать",
            key or "(без сайта)",
            len(joined),
            MAX_RULES_CHARS,
        )
        joined = joined[:MAX_RULES_CHARS].rstrip()
    return joined
