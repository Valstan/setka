"""
Celery Configuration

Конфигурация для Celery worker и beat scheduler
"""

# Broker и backend (Redis)
broker_url = "redis://localhost:6379/0"
result_backend = "redis://localhost:6379/0"

# Timezone
timezone = "Europe/Moscow"
enable_utc = False

# Task settings
task_serializer = "json"
accept_content = ["json"]
result_serializer = "json"

# Worker settings
worker_prefetch_multiplier = 1
# Переработка дочернего процесса пула. Было 1000 — и это, а не «опция не задана»,
# оказалось настоящим диагнозом OOM-убийств (найдено 2026-09-14).
#
# **Замер на проде, а не оценка.** Воркер завершает 250–380 задач в час (среднее
# ~300, считано по строкам «succeeded in» за сутки), ядро одно → concurrency 1 →
# дочерний процесс ровно один. При пороге 1000 он переживает **3.3 часа**, а
# ядро убивает его раньше: по `dmesg` восемь OOM-убийств за 09.09–14.09, RSS в
# момент смерти 390–518 МБ при 1536 МБ на боксе и **swap = 0**. Свежий ребёнок
# занимает ~87 МБ, то есть память копится до потолка внутри одного интервала
# переработки — порог просто не успевает сработать.
#
# 250 задач ≈ 50 минут при нынешнем темпе: ребёнок перерабатывается втрое чаще,
# чем растёт до опасного размера. Цена — форк с ре-импортом приложения примерно
# раз в час на 7000 задач в сутки; на фоне 1 ядра это шум.
#
# Почему не через `--max-tasks-per-child` в ExecStart юнита: конфиг уже здесь и
# уже применяется (`app.config_from_object("config.celery_config")`). Вторая
# копия настройки в юните на проде создала бы два места правды, и первое же
# расхождение искали бы в коде, а не в systemd.
#
# Это лечение накопления, а не его причины. Течь (что именно копит память) не
# найдена — порог лишь не даёт ей дорасти до убийства. См. PENDING.
worker_max_tasks_per_child = 250

# Потолок памяти дочернего процесса (в килобайтах — так требует Celery).
# Второй предохранитель к порогу по задачам (2026-09-22, заказ владельца
# «почему не хватает памяти»). Что он делает и чего НЕ делает:
#
# * Celery сравнивает с порогом **пиковый** RSS (``ru_maxrss``) после
#   завершения каждой задачи. Одиночный всплеск внутри задачи он не остановит,
#   но как только ребёнок хоть раз перерос порог — он перерабатывается сразу
#   после этой задачи, чисто, форком, а не SIGKILL от ядра посреди
#   ``wall.post``.
# * 350 МБ — ниже нижней границы наблюдаемых убийств (390 МБ, ``dmesg``
#   09.09–14.09) и вчетверо больше свежего ребёнка (~87 МБ): обычная волна
#   (+50…150 МБ) порог не задевает, накопление — задевает.
# * Срабатывает тот из двух порогов, что наступит первым.
#
# Снимок бокса 2026-09-22, подтверждающий выбор: ``nproc`` = 1, дочерний
# процесс РОВНО ОДИН (значит потолок не умножается на число детей), и за 23
# минуты жизни он уже занимал **268 МБ** при 324 МБ свободных на боксе. То
# есть между нормальной работой и полосой убийств зазор меньше сотни мегабайт,
# и порог 350 ложится в него: ребёнок переработается сам, не дожидаясь ядра.
worker_max_memory_per_child = 350 * 1024

# Ограничение времени задачи. Ядро одно, concurrency 1: зависшая задача
# (сокет ВК, замок в БД) блокирует ВСЕ beat-задачи, включая поминутные
# диспетчеры. Жёсткий лимит убивает дочерний процесс — ровно то же, что делает
# ядро при OOM, и этот отказ система уже переносит: ``task_acks_late`` вместе с
# ``task_reject_on_worker_lost`` возвращают задачу в очередь.
#
# **Мягкого лимита здесь НЕТ, и это осознанный отказ, а не недосмотр.**
# Почти все задачи синхронные снаружи и асинхронные внутри: они крутят корутину
# через ``utils/celery_asyncio.run_coro``, то есть ``loop.run_until_complete``
# на ОДНОМ персистентном цикле процесса (иначе пул asyncpg разваливается —
# см. докстринг того модуля). ``SoftTimeLimitExceeded`` прилетает сигналом в
# тот же поток и выбрасывает управление из ``run_until_complete``, но саму
# корутину НЕ отменяет: она остаётся висеть на общем цикле. Задача при этом
# «завершается» ошибкой, воркер берёт следующую — и недобитая корутина
# продолжает исполняться вперемежку с ней, держа соединение из пула (размер 3)
# и досылая свои побочные действия, вплоть до публикации. Получилось бы, что
# защита от зависания порождает отказ страшнее зависания, и притом молчаливый.
# Жёсткий лимит такого не умеет: он убивает процесс целиком вместе с циклом.
#
# **Границы взяты из замера, а не на глаз** (журналы воркера, 2026-09-22,
# максимум по каждой задаче за двое суток):
#
#   1750 с  recheck_all_active_regions  ← недельный обход, СВОИ лимиты в задаче
#    368 с  parse_and_publish_theme
#    310 с  classify_pending_posts
#    230 с  refresh_post_metrics
#    103 с  check_recent_comments
#
# То есть у всего, что ходит по расписанию чаще раза в неделю, запас
# девятикратный. Единственная задача, которой общего лимита мало, объявляет
# свой прямо в декораторе (``tasks/discovery_tasks.py``) — там же и почему.
task_time_limit = 3600

# Task result settings
result_expires = 3600  # 1 час

# Task execution
task_acks_late = True
task_reject_on_worker_lost = True

# Logging
worker_log_format = "[%(asctime)s: %(levelname)s/%(processName)s] %(message)s"
worker_task_log_format = (
    "[%(asctime)s: %(levelname)s/%(processName)s] [%(task_name)s(%(task_id)s)] %(message)s"
)
