"""Конфиг модуля «Раскрутка» — продвижение молодых сообществ сети.

Модуль поднимает районы, которые сеть завела, но которые никто не находит: у 19
сообществ, запущенных с июля 2026, по 2–7 подписчиков. Работает четырьмя классами
действий — находимость (хэштеги, город, оформление), футер со ссылками в сводках,
промо-пост у сильного соседа, подготовка кандидатов для РУЧНОГО аутрича владельца.

**Чего модуль не делает никогда.** Не пишет на чужие стены, не рассылает личных
сообщений, не приглашает в сообщества и не заводит дополнительных аккаунтов.
Это не осторожность на всякий случай: правила VK определяют спам как «рассылку
рекламной или другой информации с помощью инструментов, которые не предназначены
для рекламы», а дополнительные профили для такой рассылки прямо названы
бот-страницами, подлежащими удалению. Живых user-токенов у проекта два, и ими же
публикуются сводки всех 38 районов — бан гасит продукт целиком (это уже
происходило, GOTCHAS G151).

Env vars:
  PROMO_DISABLED=1            # kill-switch. ДЕФОЛТ — ВЫКЛЮЧЕНО, в отличие от
                              # BROADCAST_DISABLED: рассылку заводит оператор явным
                              # действием, а раскрутка публикует сама по расписанию.
  PROMO_MAX_ACTIONS_PER_DAY=3 # аварийный потолок действий в сутки поверх БД-настройки
  PROMO_REGION_CODES          # allowlist кодов районов (CSV); пусто = все активные
  PROMO_POST_INTERVAL_SECONDS=5.0   # пауза между реальными публикациями (анти-капча:
                                    # замер broadcast — 16 постов по 5 с без капчи,
                                    # бурст по 3 с капчу ловит)
  PROMO_VALSTAN_CALL_BUDGET=50      # потолок вызовов VALSTAN за сутки, после которого
                                    # каналы, требующие user-токена, пропускаются
  PROMO_OBLAST_GROUP_ID       # донор-фолбэк для районов без сильного соседа;
                              # дефолт — областная группа сети
"""

from __future__ import annotations

import logging
import os
from typing import List

logger = logging.getLogger(__name__)

_TRUE = ("1", "true", "yes", "on")

# Областная группа сети — донор последней надежды для районов, у которых нет ни
# одного сильного соседа ни на первом, ни на втором хопе (замер 28.08: таких 11 из
# 24). Рычаг слабый — в ней 953 подписчика на всю область, — и UI обязан говорить
# об этом прямо, а не делать вид, что район «в работе».
DEFAULT_OBLAST_GROUP_ID = -168170001

# Каналы модуля. Значение — «пишет ли канал в VK»: у чисто локальных (hashtags,
# footer) обращений к API нет вовсе, и dry-run для них означает лишь «не трогать БД».
CHANNELS = (
    "hashtags",
    "city",
    "setup",
    "pin",
    "footer",
    "promo_post",
    "oblast_digest",
    "outreach",
)

# Каналы, которым разрешён user-токен. Всё остальное ходит community-токеном
# сообщества-донора, то есть не расходует аккаунт, чья потеря гасит публикацию сети.
USER_TOKEN_CHANNELS = frozenset({"setup"})


def promo_disabled() -> bool:
    """Kill-switch модуля (env ``PROMO_DISABLED``). **Дефолт — выключен.**

    Дефолт отличается от ``broadcast_disabled`` намеренно. Там безопасность держится
    тем, что кампанию должен явно создать оператор; здесь планировщик сам находит
    пары «донор → цель» и сам публикует, поэтому невзведённый флаг обязан означать
    тишину, а не работу.
    """
    return os.getenv("PROMO_DISABLED", "1").strip().lower() in _TRUE


def get_max_actions_per_day() -> int:
    """Аварийный суточный потолок действий (env ``PROMO_MAX_ACTIONS_PER_DAY``).

    Поверх настройки в БД: env всегда сильнее, чтобы потолок можно было опустить
    без похода в UI. Границы 0..50; 0 = «не публиковать ничего».
    """
    try:
        return max(0, min(50, int(os.getenv("PROMO_MAX_ACTIONS_PER_DAY", "3"))))
    except ValueError:
        return 3


def get_region_allowlist() -> List[str]:
    """Коды районов, которым разрешена раскрутка (env ``PROMO_REGION_CODES``, CSV).

    Пусто → пустой список → «все активные районы» (вызывающий читает это как
    отсутствие фильтра). Нужен для обкатки на одном районе.
    """
    raw = os.getenv("PROMO_REGION_CODES", "") or ""
    return [c.strip() for c in raw.replace(";", ",").split(",") if c.strip()]


def get_post_interval_seconds() -> float:
    """Пауза между реальными публикациями (env ``PROMO_POST_INTERVAL_SECONDS``).

    Пять секунд — не круглое число «на всякий случай», а замеренная граница:
    сетевая рассылка прошла 16 постов подряд с интервалом 5 с без единой капчи,
    а бурст с интервалом 3 с капчу ловит. Границы 1..60.
    """
    try:
        return max(1.0, min(60.0, float(os.getenv("PROMO_POST_INTERVAL_SECONDS", "5.0"))))
    except ValueError:
        return 5.0


def get_valstan_call_budget() -> int:
    """Потолок вызовов VALSTAN за сутки для каналов раскрутки (env ``PROMO_VALSTAN_CALL_BUDGET``).

    VALSTAN — последний рубеж каскада публикации всех 38 районов. Раскрутка не
    имеет права выесть его бюджет: превышен — каналы, требующие user-токена,
    молча пропускаются до следующих суток. Границы 0..500.
    """
    try:
        return max(0, min(500, int(os.getenv("PROMO_VALSTAN_CALL_BUDGET", "50"))))
    except ValueError:
        return 50


def get_oblast_group_id() -> int:
    """Донор-фолбэк для районов без сильного соседа (env ``PROMO_OBLAST_GROUP_ID``)."""
    raw = (os.getenv("PROMO_OBLAST_GROUP_ID") or "").strip()
    if not raw:
        return DEFAULT_OBLAST_GROUP_ID
    try:
        return int(raw)
    except ValueError:
        logger.warning("PROMO_OBLAST_GROUP_ID=%r не число, беру дефолт", raw)
        return DEFAULT_OBLAST_GROUP_ID
