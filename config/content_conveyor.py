def conveyor_disabled() -> bool:
    """Kill-switch всего конвейера (env ``CONVEYOR_DISABLED``). Дефолт — включён."""
    return os.getenv("CONVEYOR_DISABLED", "0").strip().lower() in ("1", "true", "yes", "on")


def get_enabled_site_keys() -> List[str]:
    """Ключи активных сайтов (env ``CONVEYOR_SITES``, CSV).

    Пусто → пустой список → **ни один сайт не активен**. Это осознанно строже,
    чем у классификатора (там пустой allowlist = «все регионы»): там пустое
    значение включает shadow-чтение, здесь — исходящую доставку на публичный
    сайт. Умолчание, которое начинает публиковать, — не то умолчание, которое
    хочется получить, забыв переменную при переезде на новый бокс.
    """
    raw = os.getenv("CONVEYOR_SITES", "") or ""
    return [c.strip().lower() for c in raw.replace(";", ",").split(",") if c.strip()]


def get_site(key: str) -> Optional[Dict[str, object]]:
    """Описание сайта по ключу (без учёта активности). Нет такого — ``None``."""
    k = (key or "").strip().lower()
    for site in SITES:
        if str(site["key"]).lower() == k:
            return dict(site)
    return None


def get_active_sites() -> List[Dict[str, object]]:
    """Описания сайтов, которые сейчас разрешено обслуживать.

    Пересечение ``SITES`` и ``CONVEYOR_SITES``; при выключенном конвейере —
    пусто. Ключ из env, которому нет описания, молча игнорируется: опечатка в
    переменной не должна ронять прогон остальных сайтов.
    """
    if conveyor_disabled():
        return []
    allow = set(get_enabled_site_keys())
    if not allow:
        return []
    return [dict(s) for s in SITES if str(s["key"]).lower() in allow]


def get_ingest_key(site: Dict[str, object]) -> str:
    """Секрет доставки для сайта из env по имени ``key_env``. Пусто = не настроен."""
    name = str(site.get("key_env") or "").strip()
    if not name:
        return ""
    return (os.getenv(name) or "").strip()


def get_source_days() -> int:
    """Окно свежести источника в сутках (env ``CONVEYOR_SOURCE_DAYS``). Границы 1..30.

    Смысл тот же, что у классификатора: старая новость на сайте хуже, чем её
    отсутствие. Верхняя граница — предохранитель от «залить архив одним махом»
    при первом включении.
    """
    try:
        return max(1, min(30, int(os.getenv("CONVEYOR_SOURCE_DAYS", "3"))))
    except ValueError:
        return 3


def get_batch_max() -> int:
    """Потолок постов в одном прогоне на сайт (env ``CONVEYOR_BATCH_MAX``). Границы 1..100."""
    try:
        return max(1, min(100, int(os.getenv("CONVEYOR_BATCH_MAX", "20"))))
    except ValueError:
        return 20
