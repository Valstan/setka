#!/usr/bin/env bash
# Прибор OOM: что ядро убило на боксе и сколько памяти занято прямо сейчас.
#
# Почему отдельный скрипт, а не Celery-задача с расписанием:
#
#   1. `journalctl` на этом боксе OOM-убийств НЕ показывает — за 30 дней ноль
#      строк при восьми убийствах, видимых в `dmesg` (P164). Любой монитор,
#      построенный на journald, здесь молчит и выглядит здоровым.
#   2. Задача-прибор жила бы в тех же 1536 МБ, которые меряет, и в контейнере
#      OpenVZ `dmesg` ещё и может оказаться закрыт — тогда «прибор сломался»
#      неотличимо от «убийств не было».
#
# Только чтение. Запускается руками по SSH или из памятки /celery.
#
# ДВА ПРАВИЛА НАПИСАНИЯ, оба про молчание:
#
# * без `set -e`: `grep` без совпадений возвращает 1, и под `set -e` скрипт
#   обрывался бы ровно в хорошем случае — когда убийств нет;
# * никаких `... | tail || echo "ничего не нашлось"`: в конвейере код возврата
#   берётся от ПОСЛЕДНЕЙ команды, а `tail` успешен всегда — даже когда `grep`
#   ничего не нашёл и даже когда файла нет вовсе. Такая заглушка недостижима,
#   и «прибор сломан» выглядит как «всё чисто». Поэтому результат сначала
#   кладётся в переменную, а потом проверяется.
set -u

LOG="${SETKA_WORKER_LOG:-$HOME/SETKA/logs/celery-worker.log}"

say_or_empty() {
    # $1 — текст результата, $2 — что сказать, если результата нет.
    if [ -n "$1" ]; then
        printf '%s\n' "$1"
    else
        printf '(%s)\n' "$2"
    fi
}

echo "=== dmesg: убийства ядром (последние 20 строк) ==="
if dmesg -T >/dev/null 2>&1; then
    kills=$(dmesg -T | grep -iE 'out of memory|killed process|oom-kill' | tail -20)
    say_or_empty "$kills" "совпадений нет — убийств в буфере dmesg не найдено"
else
    echo "dmesg НЕДОСТУПЕН: нужен sudo либо закрыт в контейнере — это не 'чисто', это нет данных"
fi

echo
echo "=== celery: RSS (кБ) и время жизни процессов ==="
procs=$(ps -o pid,rss,etime,cmd -C celery --no-headers 2>/dev/null)
say_or_empty "$procs" "процессов celery не найдено — воркер не запущен?"

if [ -r "$LOG" ]; then
    echo
    echo "=== переработка дочернего процесса по памяти (лог воркера) ==="
    # Celery пишет это сам, когда сработал worker_max_memory_per_child.
    recycles=$(grep -a -iE 'exceeds maximum|max memory per child|maximum memory per child' "$LOG" | tail -5)
    say_or_empty "$recycles" "в логе пусто — порог по памяти ещё не срабатывал"

    echo
    echo "=== рост пика RSS по задачам (прибор из tasks/celery_app.py) ==="
    mem=$(grep -a 'mem: task=' "$LOG" | tail -15)
    say_or_empty "$mem" "строк прибора нет — воркер ещё не перезапускался с этой версией"

    echo
    echo "=== потери воркера (убитый ребёнок уносит задачу) ==="
    lost=$(grep -a -E 'WorkerLostError|Worker exited prematurely' "$LOG" | tail -5)
    say_or_empty "$lost" "потерь в текущем логе нет"
else
    echo
    echo "лог воркера не читается: $LOG — проверьте путь или права (SETKA_WORKER_LOG переопределяет)"
fi

echo
echo "=== память бокса ==="
free -m
